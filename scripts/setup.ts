/**
 * Generates machine-local secrets for development.
 *
 * Creates or updates two gitignored files:
 *   .env                 read by docker-compose (SQL Server admin password and host port)
 *   local.settings.json  read by the Functions host (database connection settings)
 *
 * Safe to run repeatedly: an existing password is kept, because SQL Server only applies
 * the password when its data volume is first created. Pass --force to generate a new one,
 * then recreate the database container with `docker compose down -v`.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

// Compiled to dist/scripts/setup.js, so the repo root is two levels up.
const ROOT = resolve(__dirname, '..', '..');
const ENV_FILE = join(ROOT, '.env');
const SETTINGS_FILE = join(ROOT, 'local.settings.json');
const SETTINGS_EXAMPLE_FILE = join(ROOT, 'local.settings.example.json');
const DEFAULT_PORT = '14333';

interface LocalSettings {
  IsEncrypted: boolean;
  Values: Record<string, string>;
  [key: string]: unknown;
}

/**
 * 24 random URL-safe characters plus an upper-case letter, a lower-case letter and a digit.
 * Meets SQL Server's password policy and avoids characters that need escaping in .env files.
 */
function generatePassword(): string {
  return randomBytes(18).toString('base64url') + 'Aa1';
}

function readEnvFile(file: string): Record<string, string> {
  const values: Record<string, string> = {};
  if (!existsSync(file)) return values;

  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const [, key, value] = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line) ?? [];
    if (key !== undefined && value !== undefined) values[key] = value;
  }
  return values;
}

function readSettings(): LocalSettings {
  const source = existsSync(SETTINGS_FILE) ? SETTINGS_FILE : SETTINGS_EXAMPLE_FILE;
  if (!existsSync(source)) {
    throw new Error('local.settings.example.json is missing. Restore it from git and try again.');
  }
  return JSON.parse(readFileSync(source, 'utf8')) as LocalSettings;
}

function main(): void {
  const force = process.argv.includes('--force');
  const existingEnv = readEnvFile(ENV_FILE);

  const keepPassword = !force && existingEnv.SQL_PASSWORD !== undefined && !existingEnv.SQL_PASSWORD.startsWith('<');
  const password = keepPassword ? existingEnv.SQL_PASSWORD! : generatePassword();
  const port = existingEnv.SQL_PORT ?? DEFAULT_PORT;

  writeFileSync(
    ENV_FILE,
    [
      '# Generated by `npm run setup`. Local development only. Never commit this file.',
      `SQL_PASSWORD=${password}`,
      `SQL_PORT=${port}`,
      '',
    ].join('\n'),
  );

  const settings = readSettings();
  settings.Values.SQL_PASSWORD = password;
  settings.Values.SQL_PORT = port;
  writeFileSync(SETTINGS_FILE, JSON.stringify(settings, null, 2) + '\n');

  console.log(keepPassword ? 'Kept the existing local SQL password.' : 'Generated a new local SQL password.');
  console.log('Wrote .env and local.settings.json (both gitignored).');
  if (force) {
    console.log('Run `docker compose down -v` before starting the database so the new password is applied.');
  }
}

try {
  main();
} catch (error) {
  console.error(`Setup failed: ${(error as Error).message}`);
  process.exitCode = 1;
}
