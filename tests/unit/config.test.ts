import { describe, expect, it } from 'vitest';
import { ConfigurationError, readDatabaseSettings, toMssqlConfig } from '../../src/db/config';

const localEnv = {
  SQL_AUTH: 'sql',
  SQL_SERVER: 'localhost',
  SQL_PORT: '14333',
  SQL_DATABASE: 'Compensation',
  SQL_USER: 'sa',
  SQL_PASSWORD: 'Secret123',
  SQL_TRUST_SERVER_CERTIFICATE: 'true',
};

describe('readDatabaseSettings', () => {
  it('reads SQL login settings for the local database', () => {
    expect(readDatabaseSettings(localEnv)).toEqual({
      server: 'localhost',
      port: 14333,
      database: 'Compensation',
      auth: 'sql',
      user: 'sa',
      password: 'Secret123',
      trustServerCertificate: true,
    });
  });

  it('needs no user or password for Entra authentication', () => {
    const settings = readDatabaseSettings({ SQL_AUTH: 'entra', SQL_SERVER: 'x.database.windows.net', SQL_DATABASE: 'db' });
    expect(settings).toMatchObject({ auth: 'entra', port: 1433, trustServerCertificate: false });
    expect(settings.password).toBeUndefined();
  });

  it('lists every missing setting in one error', () => {
    expect(() => readDatabaseSettings({ SQL_AUTH: 'sql' })).toThrow(
      'Missing database settings: SQL_SERVER, SQL_DATABASE, SQL_USER, SQL_PASSWORD.',
    );
  });

  it('rejects the placeholder password from the example file', () => {
    expect(() => readDatabaseSettings({ ...localEnv, SQL_PASSWORD: '<generated by npm run setup>' })).toThrow(/npm run setup/);
  });

  it('rejects an unknown auth mode and an invalid port', () => {
    expect(() => readDatabaseSettings({ ...localEnv, SQL_AUTH: 'windows' })).toThrow(ConfigurationError);
    expect(() => readDatabaseSettings({ ...localEnv, SQL_PORT: '99999' })).toThrow(/SQL_PORT/);
  });
});

describe('toMssqlConfig', () => {
  it('uses a SQL login locally and always encrypts', () => {
    const config = toMssqlConfig(readDatabaseSettings(localEnv));
    expect(config).toMatchObject({ user: 'sa', password: 'Secret123', options: { encrypt: true, trustServerCertificate: true } });
  });

  it('uses a token credential, not a password, for Entra', () => {
    const config = toMssqlConfig(readDatabaseSettings({ SQL_AUTH: 'entra', SQL_SERVER: 's', SQL_DATABASE: 'd' }));
    expect(config.password).toBeUndefined();
    expect(config.authentication?.type).toBe('token-credential');
  });

  it('can target another database on the same server', () => {
    expect(toMssqlConfig(readDatabaseSettings(localEnv), 'master').database).toBe('master');
  });
});
